import 'dart:async';

import 'package:analyzer/dart/element/element.dart';
import 'package:analyzer/dart/element/type.dart';
import 'package:build/build.dart';
import 'package:glob/glob.dart';
import 'package:source_gen/source_gen.dart';
import 'package:witch_doctor/witch_doctor.dart';

/// An aggregating builder that collects every `@Remedy` annotated class in a
/// package and emits a single `lib/witch_doctor.init.dart` exposing
/// `initRemedies(Dispensary)`.
///
/// For each annotated class it reads the unnamed constructor and wires every
/// parameter by resolving it from the [Injector], injectable style:
///
/// ```dart
/// void initRemedies(Dispensary dispensary) {
///   dispensary.registerLazySingleton<Greeter>((i) => EnglishGreeter());
///   dispensary.registerFactory<GreetingService>((i) => GreetingService(i<Greeter>()));
/// }
/// ```
class RemedyInitBuilder implements Builder {
  static final TypeChecker _remedyChecker = TypeChecker.typeNamed(
    Remedy,
    inPackage: 'witch_doctor',
  );

  @override
  Map<String, List<String>> get buildExtensions => const {
    r'$lib$': ['witch_doctor.init.dart'],
  };

  @override
  Future<void> build(BuildStep buildStep) async {
    final registrations = <_Registration>[];

    await for (final input in buildStep.findAssets(Glob('lib/**.dart'))) {
      if (input.path.endsWith('.init.dart') || input.path.endsWith('.g.dart')) {
        continue;
      }
      if (!await buildStep.resolver.isLibrary(input)) continue;

      final library = await buildStep.resolver.libraryFor(input);
      for (final annotated in LibraryReader(
        library,
      ).annotatedWith(_remedyChecker)) {
        final element = annotated.element;
        if (element is! ClassElement) {
          throw InvalidGenerationSourceError(
            '@Remedy can only annotate classes.',
            element: element,
          );
        }
        registrations.add(
          _readRegistration(element, annotated.annotation, input),
        );
      }
    }

    if (registrations.isEmpty) return;

    registrations.sort((a, b) => a.key.compareTo(b.key));

    final imports = <String>{'package:witch_doctor/witch_doctor.dart'};
    for (final r in registrations) {
      imports.addAll(r.imports);
    }
    final sortedImports = imports.toList()..sort();

    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
      ..writeln('// Generated by witch_doctor_generator.')
      ..writeln()
      ..writeln('// ignore_for_file: type=lint, unused_import')
      ..writeln();
    for (final import in sortedImports) {
      buffer.writeln("import '$import';");
    }
    buffer
      ..writeln()
      ..writeln(
        '/// Registers every `@Remedy` annotated class into [dispensary].',
      )
      ..writeln('void initRemedies(Dispensary dispensary) {');
    for (final r in registrations) {
      buffer.writeln('  ${r.statement}');
    }
    buffer.writeln('}');

    final outputId = AssetId(
      buildStep.inputId.package,
      'lib/witch_doctor.init.dart',
    );
    await buildStep.writeAsString(outputId, buffer.toString());
  }

  _Registration _readRegistration(
    ClassElement element,
    ConstantReader annotation,
    AssetId input,
  ) {
    final className = element.name;
    if (className == null) {
      throw InvalidGenerationSourceError(
        '@Remedy cannot be used on an unnamed class.',
        element: element,
      );
    }

    final imports = <String>{
      'package:${input.package}/${input.path.substring('lib/'.length)}',
    };

    // Resolution key: the `as:` type, defaulting to the class itself.
    final asReader = annotation.read('as');
    String key = className;
    if (!asReader.isNull) {
      final asType = asReader.typeValue;
      key = _displayName(asType);
      final uri = _importUriOf(asType);
      if (uri != null) imports.add(uri);
    }

    // Wire constructor parameters.
    final ctor = element.unnamedConstructor;
    final args = <String>[];
    for (final param
        in ctor?.formalParameters ?? const <FormalParameterElement>[]) {
      final type = param.type;
      final uri = _importUriOf(type);
      if (uri == null || uri.startsWith('dart:')) {
        throw InvalidGenerationSourceError(
          'Cannot auto-wire parameter `${param.name}` of `$className`: type '
          '`${_displayName(type)}` is not an injectable type. Register '
          '`$className` manually with dispensary.register*(), or make the '
          'parameter a registered dependency.',
          element: element,
        );
      }
      imports.add(uri);
      final expr = 'i<${_displayName(type)}>()';
      args.add(param.isNamed ? '${param.name}: $expr' : expr);
    }

    final ctorCall = '$className(${args.join(', ')})';
    final scope = _readScope(annotation);
    final statement = switch (scope) {
      Scope.transient => 'dispensary.registerFactory<$key>((i) => $ctorCall);',
      // Annotation singletons are shared instances created lazily so their
      // dependencies resolve from the loaded graph.
      Scope.singleton || Scope.lazySingleton =>
        'dispensary.registerLazySingleton<$key>((i) => $ctorCall);',
    };

    return _Registration(key: key, statement: statement, imports: imports);
  }

  Scope _readScope(ConstantReader annotation) {
    final index = annotation
        .read('scope')
        .objectValue
        .getField('index')
        ?.toIntValue();
    return switch (index) {
      1 => Scope.singleton,
      2 => Scope.lazySingleton,
      _ => Scope.transient,
    };
  }

  String _displayName(DartType type) => type.getDisplayString();

  String? _importUriOf(DartType type) {
    final element = type.element;
    final uri = element?.library?.uri;
    return uri?.toString();
  }
}

class _Registration {
  _Registration({
    required this.key,
    required this.statement,
    required this.imports,
  });

  final String key;
  final String statement;
  final Set<String> imports;
}
